// These files are repository-specific and may be regenerated in the public
// checkout instead of copied byte-for-byte from the mirror.
export const PUBLIC_GENERATED_PATHS = Object.freeze(["package-lock.json"]);

// The export report is generated by the mirror builder but remains an exact,
// hash-bound public-sync file rather than a regeneration exception.
export const PUBLIC_MIRROR_MANIFEST_PATH = "MIRROR-MANIFEST.json";

export const PUBLIC_SYNC_MANIFEST_PATH = ".grp-public-sync.json";

export const PUBLIC_REPOSITORY_ORIGINS = Object.freeze([
  "git@github.com:Group-Resolution-Protocol/grp.git",
  "https://github.com/Group-Resolution-Protocol/grp",
  "https://github.com/Group-Resolution-Protocol/grp.git",
]);

const sourceExcludes = new Set(PUBLIC_SOURCE_EXCLUDES);
const rootMapping = new Map(PUBLIC_ROOT_MAPPINGS);
const publicRootDestinations = new Set(PUBLIC_ROOT_MAPPINGS.map(([, destination]) => destination));
const generatedDestinations = new Set([...PUBLIC_GENERATED_PATHS, PUBLIC_MIRROR_MANIFEST_PATH]);

export function normalizeRepoPath(value) {
  return String(value).replaceAll("\\", "/").replace(/^\.\//, "").replace(/\/$/, "");
}

export function isCanonicalRepoPath(value) {
  if (typeof value !== "string" || value.length === 0 || value !== normalizeRepoPath(value)) {
    return false;
  }
  if (
    value.startsWith("/") ||
    value.includes("\\") ||
    [...value].some((character) => {
      const codePoint = character.codePointAt(0);
      return codePoint !== undefined && (codePoint <= 31 || codePoint === 127);
    })
  ) {
    return false;
  }
  return value.split("/").every((segment) => segment !== "" && segment !== "." && segment !== "..");
}

export function publicDestinationForSource(sourcePath) {
  if (!isCanonicalRepoPath(sourcePath)) return undefined;
  const normalized = normalizeRepoPath(sourcePath);
  if (sourceExcludes.has(normalized)) return undefined;
  const mapped = rootMapping.get(normalized);
  if (mapped) return mapped;
  for (const root of PUBLIC_SOURCE_ROOTS) {
    if (normalized === root || normalized.startsWith(`${root}/`)) return normalized;
  }
  if (normalized === "tsconfig.base.json") return normalized;
  return undefined;
}

export function isAllowedPublicDestination(destinationPath) {
  if (!isCanonicalRepoPath(destinationPath)) return false;
  const normalized = normalizeRepoPath(destinationPath);
  if (normalized === PUBLIC_SYNC_MANIFEST_PATH) return true;
  if (publicRootDestinations.has(normalized) || generatedDestinations.has(normalized)) return true;
  if (normalized === "tsconfig.base.json") return true;
  return PUBLIC_SOURCE_ROOTS.some((root) => normalized.startsWith(`${root}/`));
}

export function publicChangeDestinations(sourcePaths) {
  return [
    ...new Set(sourcePaths.map(publicDestinationForSource).filter((value) => value !== undefined)),
  ].sort();
}
